//! The icons offered by Insert > Icons. Each one is a character of the Windows icon font that is inserted as editable
//! text (any color, size, outline, shadow), so it stays sharp at any size (C# `IconCatalog`).

/// One icon of the built-in set.
pub struct IconItem {
    pub category: &'static str,
    pub name: &'static str,
    pub code: u32,
}

impl IconItem {
    /// The icon as the one character of the icon font.
    pub fn glyph(&self) -> String {
        char::from_u32(self.code).map(String::from).unwrap_or_default()
    }
}

/// The font the icons come from (Windows 11 first, the older Windows 10 font as backup).
